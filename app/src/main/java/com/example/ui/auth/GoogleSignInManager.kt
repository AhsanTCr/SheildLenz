package com.example.ui.auth

import android.app.Activity
import android.content.Context
import android.content.ContextWrapper
import android.util.Log
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.Firebase
import com.google.firebase.FirebaseApp
import com.google.firebase.FirebaseOptions
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.auth
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.NonCancellable
import kotlinx.coroutines.launch
import kotlinx.coroutines.tasks.await
import kotlinx.coroutines.withContext

/**
 * Centralized Jetpack Credential Manager + Firebase Auth Google Sign-In helper.
 *
 * Guarantees Firebase is initialized and web client ID is resolved, with full fallback
 * programmatic FirebaseOptions and client ID support.
 */
object GoogleSignInManager {
    private const val TAG = "Auth"

    const val FIREBASE_APPLICATION_ID = "1:206265135684:android:884d0ff4f5cbc8d2970211"
    const val FIREBASE_API_KEY = "AIzaSyDvE6h_mQF6-58S88Hx18AnEHz5XP5XGAM"
    const val FIREBASE_PROJECT_ID = "gen-lang-client-0700550101"
    const val FIREBASE_GCM_SENDER_ID = "206265135684"
    const val FIREBASE_STORAGE_BUCKET = "gen-lang-client-0700550101.firebasestorage.app"

    /**
     * Default Web Client ID configured for this Firebase project (gen-lang-client-0700550101).
     * Used as a robust fallback in CI and release environments where google-services.json
     * may not have generated R.string.default_web_client_id.
     */
    const val DEFAULT_WEB_CLIENT_ID = "206265135684-sh14t7ig3uimgrp5guqttdi18rbdj8hk.apps.googleusercontent.com"

    fun ensureFirebaseInitialized(context: Context): Boolean {
        val appContext = context.applicationContext
        if (FirebaseApp.getApps(appContext).isNotEmpty()) return true

        // 1. First try standard zero-arg initializeApp (reads XML resources generated by google-services)
        val defaultInitSuccess = runCatching {
            FirebaseApp.initializeApp(appContext) != null
        }.getOrDefault(false)

        if (defaultInitSuccess && FirebaseApp.getApps(appContext).isNotEmpty()) {
            return true
        }

        // 2. Programmatic fallback initialization with project credentials
        // Guarantees Firebase is initialized even if google-services.json was missing or stripped during build
        return runCatching {
            val options = FirebaseOptions.Builder()
                .setApplicationId(FIREBASE_APPLICATION_ID)
                .setApiKey(FIREBASE_API_KEY)
                .setProjectId(FIREBASE_PROJECT_ID)
                .setGcmSenderId(FIREBASE_GCM_SENDER_ID)
                .setStorageBucket(FIREBASE_STORAGE_BUCKET)
                .build()
            FirebaseApp.initializeApp(appContext, options)
            true
        }.onFailure {
            Log.e(TAG, "Fallback programmatic Firebase initialization failed: ${it.message}", it)
        }.getOrDefault(false)
    }

    tailrec fun Context.findActivity(): Activity? = when (this) {
        is Activity -> this
        is ContextWrapper -> baseContext.findActivity()
        else -> null
    }

    fun resolveWebClientId(context: Context): String {
        val resId = runCatching {
            context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        }.getOrDefault(0)

        if (resId != 0) {
            val resolved = runCatching { context.getString(resId).trim() }.getOrDefault("")
            if (resolved.isNotBlank()) return resolved
        }

        val appResId = runCatching {
            context.applicationContext.resources.getIdentifier(
                "default_web_client_id",
                "string",
                context.applicationContext.packageName
            )
        }.getOrDefault(0)

        if (appResId != 0) {
            val resolved = runCatching { context.applicationContext.getString(appResId).trim() }.getOrDefault("")
            if (resolved.isNotBlank()) return resolved
        }

        return DEFAULT_WEB_CLIENT_ID
    }

    suspend fun attemptAutoSignIn(
        context: Context,
        credentialManager: CredentialManager,
        onAuthSuccess: () -> Unit = {}
    ) {
        if (!ensureFirebaseInitialized(context)) return
        if (runCatching { Firebase.auth.currentUser != null }.getOrDefault(false)) {
            onAuthSuccess()
            return
        }
        val clientId = resolveWebClientId(context)
        if (clientId.isBlank()) return

        val googleIdOption = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(true)
            .setServerClientId(clientId)
            .setAutoSelectEnabled(true)
            .build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(googleIdOption)
            .build()

        try {
            val activity = context.findActivity() ?: return
            val response = credentialManager.getCredential(activity, request)
            val credential = response.credential
            if (credential is CustomCredential &&
                credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
            ) {
                val idToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                Firebase.auth.signInWithCredential(
                    GoogleAuthProvider.getCredential(idToken, null)
                ).await()
                onAuthSuccess()
            }
        } catch (ce: CancellationException) {
            throw ce
        } catch (e: Exception) {
            Log.d(TAG, "Silent Google auto sign-in skipped: ${e.message}")
        }
    }

    fun signInWithGoogle(
        context: Context,
        credentialManager: CredentialManager? = null,
        scope: CoroutineScope,
        onAuthSuccess: () -> Unit,
        onAuthCancelled: () -> Unit,
        onAuthError: (String) -> Unit
    ) {
        val activity = context.findActivity()
        if (activity == null) {
            onAuthError("Open Sheildlenz inside the main app window to sign in.")
            return
        }

        if (!ensureFirebaseInitialized(activity)) {
            onAuthError("Firebase could not be initialized on device. Please check network connection and retry.")
            return
        }

        val clientId = resolveWebClientId(activity)
        if (clientId.isBlank()) {
            onAuthError("Google Sign-In configuration missing: default_web_client_id not found.")
            return
        }

        val activeCredentialManager = credentialManager ?: CredentialManager.create(activity)
        val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(signInOption)
            .build()

        scope.launch {
            try {
                val result = activeCredentialManager.getCredential(activity, request)
                val credential = result.credential
                if (credential is CustomCredential &&
                    credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
                ) {
                    val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                    val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
                    Firebase.auth.signInWithCredential(authCredential).await()
                    onAuthSuccess()
                } else {
                    onAuthError("Unexpected credential type returned by Google Sign-In.")
                }
            } catch (e: GetCredentialCancellationException) {
                Log.w(TAG, "Google Sign-In flow cancelled or dismissed: ${e.message}", e)
                onAuthCancelled()
            } catch (e: NoCredentialException) {
                Log.w(TAG, "No Google credentials available on device: ${e.message}", e)
                onAuthError("No Google account found on this device. Add a Google account in device Settings and retry.")
            } catch (ce: CancellationException) {
                throw ce
            } catch (e: Exception) {
                Log.e(TAG, "Google Sign-In failed", e)
                onAuthError(e.localizedMessage ?: "Google Sign-In failed.")
            }
        }
    }

    fun signOut(
        context: Context,
        credentialManager: CredentialManager? = null,
        scope: CoroutineScope,
        onSignOutComplete: () -> Unit = {}
    ) {
        val activeManager = credentialManager ?: CredentialManager.create(context.applicationContext)
        scope.launch {
            withContext(NonCancellable) {
                try {
                    activeManager.clearCredentialState(ClearCredentialStateRequest())
                } catch (e: Exception) {
                    Log.w(TAG, "Failed to clear credential state: ${e.message}")
                } finally {
                    runCatching { Firebase.auth.signOut() }
                    onSignOutComplete()
                }
            }
        }
    }
}
